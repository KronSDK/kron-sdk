#!/usr/bin/env node
// Writes src/walletMatrix/referenceTemplates.ts — the token and curve programs the wallet matrix builds its four shapes
// with, copied from src/native/__fixtures__/kcc20v1-templates.json (silverc v1.0.0 output for the fixture's test params,
// itself written by `node scripts/verify-parity-v1.mjs --write-fixture`). Only these two programs are carried: the
// matrix needs no pool or order program. Re-run after the fixture is regenerated; the walletMatrix vitest suite fails
// while the two disagree.
//   node scripts/gen-wallet-matrix-templates.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const SDK = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const FIXTURE = `${SDK}/src/native/__fixtures__/kcc20v1-templates.json`;
const OUT = `${SDK}/src/walletMatrix/referenceTemplates.ts`;

const fx = JSON.parse(readFileSync(FIXTURE, 'utf8'));
const program = (p) => ({ name: p.name, bytecodeHex: p.bytecodeHex, stateSpan: p.stateSpan, prefixLen: p.prefixLen, suffixLen: p.suffixLen, templateHash: p.templateHash, dispatchTags: p.dispatchTags });
const data = { schema: fx.templateVersion?.schema ?? null, params: fx.params, token: program(fx.token), curve: program(fx.curve) };

const src = `// GENERATED by scripts/gen-wallet-matrix-templates.mjs from src/native/__fixtures__/kcc20v1-templates.json. Do not edit.
// The kcc20v1 token and curve programs (silverc v1.0.0, the fixture's test params) the wallet matrix builds its shapes
// with. Their sizes match the templates KRON's /dev/wallet-matrix page compiles in the browser, so the shapes carry the
// same mass. Every template hash is recomputed from the bytes when the matrix shapes them (templatesV1.compiledFromServerV1).
import type { ServerCompiledProgramV1 } from '../native/templatesV1.js';
import type { FamilyCurveParamsInput } from '../client/templatesV1.js';

export const REFERENCE_TEMPLATES_V1: { schema: string | null; params: FamilyCurveParamsInput; token: ServerCompiledProgramV1; curve: ServerCompiledProgramV1 } = ${JSON.stringify(data, null, 1)};
`;
writeFileSync(OUT, src);
console.log(`wrote ${OUT.replace(SDK + '/', '')} (token ${data.token.bytecodeHex.length / 2} B, curve ${data.curve.bytecodeHex.length / 2} B, schema ${String(data.schema).slice(0, 12)}…)`);
